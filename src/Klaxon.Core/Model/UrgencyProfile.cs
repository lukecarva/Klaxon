using System.Text.Json.Serialization;

namespace Klaxon.Core.Model;

/// <summary>How much an alarm may intrude. Each level resolves to a full profile.</summary>
public enum UrgencyLevel
{
    /// <summary>Silent toast; passes and disappears.</summary>
    Whisper,

    /// <summary>Corner card with one beep; the default.</summary>
    Normal,

    /// <summary>Centered window that doesn't dismiss itself.</summary>
    High,

    /// <summary>Full screen on every monitor; needs a deliberate action.</summary>
    Critical,
}

/// <summary>Which kind of window the alert uses.</summary>
public enum PresentationMode
{
    /// <summary>Native Windows toast (subject to Focus Assist).</summary>
    Toast,

    /// <summary>Own card in the screen corner.</summary>
    Corner,

    /// <summary>Centered, topmost window.</summary>
    Modal,

    /// <summary>Full-screen overlay on every monitor.</summary>
    Fullscreen,
}

/// <summary>What the user must do to dismiss the alert.</summary>
public enum DismissMode
{
    /// <summary>Disappears on its own.</summary>
    Auto,

    /// <summary>One click.</summary>
    Click,

    /// <summary>Hold the button for a few seconds.</summary>
    HoldButton,

    /// <summary>Type a phrase.</summary>
    TypePhrase,
}

/// <summary>What to do with an alarm that fired while the PC slept or you were away.</summary>
public enum MissedAlarmBehavior
{
    /// <summary>Forget it.</summary>
    Discard,

    /// <summary>Keep it and show as "missed" on return.</summary>
    ShowOnReturn,

    /// <summary>Actually fire on return.</summary>
    FireOnReturn,
}

/// <summary>How the alert sounds. Without <see cref="FilePath"/>, a tone is synthesized.</summary>
public sealed record SoundSpec
{
    /// <summary>A silent spec.</summary>
    public static SoundSpec Silent { get; } = new() { IsSilent = true };

    /// <summary>Whether no sound plays.</summary>
    public bool IsSilent { get; init; }

    /// <summary>User audio file. Null = tone generated by the app.</summary>
    public string? FilePath { get; init; }

    /// <summary>Volume, 0..1.</summary>
    public double Volume { get; init; } = 0.7;

    /// <summary>Plays until the alert is dismissed.</summary>
    public bool Loop { get; init; }

    /// <summary>Gap between repeats. <see cref="TimeSpan.Zero"/> = play once.</summary>
    public TimeSpan RepeatEvery { get; init; }

    /// <summary>Ramps the volume up gradually.</summary>
    public TimeSpan FadeIn { get; init; }
}

/// <summary>How much an alarm can be pushed back, and how many times.</summary>
public sealed record SnoozePolicy
{
    /// <summary>No snoozing allowed.</summary>
    public static SnoozePolicy None { get; } = new() { Options = [], MaxCount = 0 };

    /// <summary>Offered snooze durations.</summary>
    public required IReadOnlyList<TimeSpan> Options { get; init; }

    /// <summary>How many consecutive snoozes are allowed.</summary>
    public required int MaxCount { get; init; }

    /// <summary>Whether snoozing is possible at all.</summary>
    [JsonIgnore]
    public bool IsEnabled => MaxCount > 0 && Options.Count > 0;

    /// <summary>Default snooze duration.</summary>
    [JsonIgnore]
    public TimeSpan DefaultOption => Options.Count > 0 ? Options[0] : TimeSpan.FromMinutes(5);
}

/// <summary>The full definition of an urgency level: presentation, sound, dismissal and snooze.</summary>
public sealed record UrgencyProfile
{
    /// <summary>Which level this profile is for.</summary>
    public required UrgencyLevel Level { get; init; }

    /// <summary>How the alert is shown.</summary>
    public required PresentationMode Presentation { get; init; }

    /// <summary>How it sounds.</summary>
    public required SoundSpec Sound { get; init; }

    /// <summary>Null = the alert stays until the user acts.</summary>
    public TimeSpan? AutoDismissAfter { get; init; }

    /// <summary>How it is dismissed.</summary>
    public required DismissMode Dismiss { get; init; }

    /// <summary>Snooze rules.</summary>
    public required SnoozePolicy Snooze { get; init; }

    /// <summary>What happens when fired while away.</summary>
    public required MissedAlarmBehavior WhenAway { get; init; }

    /// <summary>Phrase required for <see cref="DismissMode.TypePhrase"/>. Null = the localized default.</summary>
    public string? DismissPhrase { get; init; }
}

/// <summary>The four level presets.</summary>
public static class UrgencyProfiles
{
    private static readonly Dictionary<UrgencyLevel, UrgencyProfile> Presets = new()
    {
        [UrgencyLevel.Whisper] = new UrgencyProfile
        {
            Level = UrgencyLevel.Whisper,
            Presentation = PresentationMode.Toast,
            Sound = SoundSpec.Silent,
            AutoDismissAfter = TimeSpan.FromSeconds(7),
            Dismiss = DismissMode.Auto,
            Snooze = SnoozePolicy.None,
            WhenAway = MissedAlarmBehavior.Discard,
        },

        [UrgencyLevel.Normal] = new UrgencyProfile
        {
            Level = UrgencyLevel.Normal,
            Presentation = PresentationMode.Corner,
            Sound = new SoundSpec { Volume = 0.5 },
            AutoDismissAfter = TimeSpan.FromSeconds(30),
            Dismiss = DismissMode.Click,
            Snooze = new SnoozePolicy
            {
                Options = [TimeSpan.FromMinutes(5), TimeSpan.FromMinutes(10), TimeSpan.FromMinutes(15)],
                MaxCount = int.MaxValue,
            },
            WhenAway = MissedAlarmBehavior.ShowOnReturn,
        },

        [UrgencyLevel.High] = new UrgencyProfile
        {
            Level = UrgencyLevel.High,
            Presentation = PresentationMode.Modal,
            Sound = new SoundSpec { Volume = 0.7, RepeatEvery = TimeSpan.FromSeconds(10) },
            AutoDismissAfter = null,
            Dismiss = DismissMode.Click,
            Snooze = new SnoozePolicy { Options = [TimeSpan.FromMinutes(5)], MaxCount = 3 },
            WhenAway = MissedAlarmBehavior.ShowOnReturn,
        },

        [UrgencyLevel.Critical] = new UrgencyProfile
        {
            Level = UrgencyLevel.Critical,
            Presentation = PresentationMode.Fullscreen,
            Sound = new SoundSpec { Volume = 1.0, Loop = true, FadeIn = TimeSpan.FromSeconds(5) },
            AutoDismissAfter = null,
            Dismiss = DismissMode.HoldButton,
            Snooze = new SnoozePolicy { Options = [TimeSpan.FromMinutes(2)], MaxCount = 1 },
            WhenAway = MissedAlarmBehavior.FireOnReturn,
        },
    };

    /// <summary>Profile for a level.</summary>
    public static UrgencyProfile Get(UrgencyLevel level) => Presets[level];

    /// <summary>All profiles.</summary>
    public static IEnumerable<UrgencyProfile> All => Presets.Values;
}
